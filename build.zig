pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const steam = b.option(bool, "steam", "Link Steamworks (lobbies + P2P transport)") orelse true;
    const os = target.result.os.tag;
    if (os != .linux and os != .windows) @panic("eng builds for Linux and Windows only");
    const is_windows = os == .windows;

    const mod = b.createModule(.{
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .link_libcpp = true,
    });
    addPublicMacros(mod, is_windows);

    // Build options that change eng's headers travel with them, in a generated
    // eng/config.h: ENG_HAVE_STEAM changes SteamPlatform's layout, so libeng.a
    // and the game must never disagree on it (they did once in delve: the
    // engine overwrote the stack past the game's smaller SteamPlatform).
    const config = b.addWriteFiles();
    const config_h = config.add("eng/config.h", if (steam)
        "#pragma once\n// Generated by eng's build.zig.\n#define ENG_HAVE_STEAM 1\n"
    else
        "#pragma once\n// Generated by eng's build.zig: built with -Dsteam=false.\n");
    mod.addIncludePath(config.getDirectory());
    if (steam) {
        // link()/installSteamRuntime() find these on the dependency, so a
        // game can't link Steam into a non-Steam libeng or vice versa.
        b.addNamedLazyPath("steam_api_link", b.path(steamLib(is_windows, .link)));
        b.addNamedLazyPath("steam_api_runtime", b.path(steamLib(is_windows, .runtime)));
    }

    for (pc_headers_common) |pkg| addPkgConfigIncludes(b, mod, pkg);

    const cxx_flags = [_][]const u8{
        "-std=c++20",
        "-Wno-nontrivial-memcall", // imgui's memset(this, ...) constructors
    };

    // ── GLFW 3.4, built from source ──────────────────────────────────────────
    // Its own library: GLFW's sources refuse the header-option macros
    // (GLFW_INCLUDE_NONE) that eng and games are compiled with.
    const glfw = b.dependency("glfw", .{});
    const glfw_mod = b.createModule(.{ .target = target, .optimize = optimize, .link_libc = true });
    glfw_mod.addIncludePath(glfw.path("include"));
    glfw_mod.addCSourceFiles(.{ .root = glfw.path("src"), .files = &glfw_common, .flags = glfwFlags(is_windows) });
    if (is_windows) {
        glfw_mod.addCSourceFiles(.{ .root = glfw.path("src"), .files = &glfw_windows, .flags = glfwFlags(true) });
        for ([_][]const u8{ "gdi32", "user32", "shell32" }) |lib| glfw_mod.linkSystemLibrary(lib, .{});
    } else {
        for (pc_headers_linux) |pkg| addPkgConfigIncludes(b, glfw_mod, pkg);
        glfw_mod.addCSourceFiles(.{ .root = glfw.path("src"), .files = &glfw_linux, .flags = glfwFlags(false) });
        const protocols = b.addWriteFiles();
        for (wayland_protocols) |name| {
            const xml = glfw.path(b.fmt("deps/wayland/{s}.xml", .{name}));
            for ([_][2][]const u8{ .{ "client-header", "-client-protocol.h" }, .{ "private-code", "-client-protocol-code.h" } }) |kind| {
                const scan = b.addSystemCommand(&.{ "wayland-scanner", kind[0] });
                scan.addFileArg(xml);
                const out_name = b.fmt("{s}{s}", .{ name, kind[1] });
                _ = protocols.addCopyFile(scan.addOutputFileArg(out_name), out_name);
            }
        }
        glfw_mod.addIncludePath(protocols.getDirectory());
        for ([_][]const u8{ "dl", "pthread", "m" }) |lib| glfw_mod.linkSystemLibrary(lib, .{});
    }
    const glfw_lib = b.addLibrary(.{ .name = "glfw3", .linkage = .static, .root_module = glfw_mod });
    mod.linkLibrary(glfw_lib);
    mod.addIncludePath(glfw.path("include"));
    if (is_windows) {
        for ([_][]const u8{ "ws2_32", "winmm" }) |lib| mod.linkSystemLibrary(lib, .{});
    } else {
        for ([_][]const u8{ "dl", "pthread", "m" }) |lib| mod.linkSystemLibrary(lib, .{});
    }

    // ── Dear ImGui (built into eng; games include <imgui.h> through it) ──────
    const imgui = b.dependency("imgui", .{});
    mod.addCSourceFiles(.{ .root = imgui.path(""), .files = &imgui_sources, .flags = &cxx_flags });
    mod.addIncludePath(imgui.path(""));
    mod.addIncludePath(imgui.path("backends"));

    // ── Clay (UI layout; games use its CLAY() macros through <clay.h>) ───────
    // Its implementation is plain C99, compiled once here; the header also
    // compiles as C++20, which is how eng::ui and games include it.
    const clay = b.dependency("clay", .{});
    mod.addCSourceFile(.{ .file = b.path("src/ui/Clay.c"), .flags = &.{ "-std=c99", "-w" } });
    mod.addIncludePath(clay.path(""));

    // ── Shaders → SPIR-V embedded as C arrays (no runtime shader files) ──────
    const gen = b.addWriteFiles();
    for (shaders) |shader| {
        const glslc = b.addSystemCommand(&.{ "glslc", "-mfmt=c" });
        glslc.addFileArg(b.path(b.fmt("shaders/{s}", .{shader})));
        glslc.addArg("-o");
        const inc = glslc.addOutputFileArg(b.fmt("{s}.inc", .{shader}));
        _ = gen.addCopyFile(inc, b.fmt("{s}.inc", .{shader}));
    }
    mod.addIncludePath(gen.getDirectory());

    // ── eng itself ───────────────────────────────────────────────────────────
    mod.addCSourceFiles(.{ .files = &eng_sources, .flags = &cxx_flags });
    // miniaudio's implementation TU trips plenty of warnings; keep eng quiet.
    mod.addCSourceFile(.{ .file = b.path("src/audio/Audio.cpp"), .flags = &(cxx_flags ++ .{"-w"}) });
    mod.addIncludePath(b.path("include"));
    mod.addIncludePath(b.path("third_party"));
    if (steam) mod.addIncludePath(b.path(steam_sdk ++ "/public"));

    const lib = b.addLibrary(.{ .name = "eng", .linkage = .static, .root_module = mod });
    lib.installHeadersDirectory(b.path("include/eng"), "eng", .{});
    lib.installHeader(config_h, "eng/config.h");
    lib.installHeadersDirectory(imgui.path(""), "", .{ .include_extensions = &.{".h"} });
    lib.installHeadersDirectory(glfw.path("include/GLFW"), "GLFW", .{});
    lib.installHeader(clay.path("clay.h"), "clay.h");
    if (steam) lib.installHeadersDirectory(b.path(steam_sdk ++ "/public/steam"), "steam", .{});
    b.installArtifact(lib);

    // ── ui-demo: eng::ui's showcase and visual check (Linux dev builds) ─────
    //   zig build ui-demo [-- --screenshot out.png] [-- --fonts dir]
    // Linked like link() does for games, but against this build's libeng.
    if (!is_windows) {
        const demo_mod = b.createModule(.{ .target = target, .optimize = optimize, .link_libc = true, .link_libcpp = true });
        demo_mod.addCSourceFile(.{ .file = b.path("examples/ui_demo.cpp"), .flags = &cxx_flags });
        demo_mod.linkLibrary(lib);
        addPublicMacros(demo_mod, false);
        for (pc_headers_common) |pkg| addPkgConfigIncludes(b, demo_mod, pkg);
        if (steam) {
            demo_mod.addObjectFile(b.path(steamLib(false, .link)));
            demo_mod.addRPath(b.path(steam_sdk ++ "/redistributable_bin/linux64"));
        }
        demo_mod.addObjectFile(.{ .cwd_relative = vulkanLoader(b) });
        const demo = b.addExecutable(.{ .name = "ui-demo", .root_module = demo_mod });
        const run_demo = b.addRunArtifact(demo);
        run_demo.setCwd(b.path("."));
        run_demo.addPassthruArgs();
        b.step("ui-demo", "Build and run eng::ui's demo").dependOn(&run_demo.step);
    }
}

fn glfwFlags(is_windows: bool) []const []const u8 {
    return if (is_windows)
        &.{ "-std=c99", "-D_GLFW_WIN32", "-DUNICODE", "-D_UNICODE", "-w" }
    else
        &.{ "-std=c99", "-D_GLFW_X11", "-D_GLFW_WAYLAND", "-D_DEFAULT_SOURCE", "-DHAVE_MEMFD_CREATE", "-w" };
}

/// Header subtrees each pkg-config package owns, for when pkg-config gives no
/// -I because the headers sit in the default include dir (/usr/include on a
/// normal distro: pkg-config strips that). Adding all of /usr/include is fine
/// natively but breaks cross builds — Linux's libc headers then clash with
/// MinGW's or the target glibc's — so only these are copied out of it.
/// A trailing '/' marks a directory.
const pc_header_entries = [_]struct { []const u8, []const []const u8 }{
    .{ "vulkan", &.{ "vulkan/", "vk_video/" } },
    .{ "glm", &.{"glm/"} },
    .{ "x11", &.{"X11/"} },
    .{ "xcursor", &.{"X11/"} },
    .{ "xrandr", &.{"X11/"} },
    .{ "xinerama", &.{"X11/"} },
    .{ "xi", &.{"X11/"} },
    .{ "xext", &.{"X11/"} },
    .{ "xrender", &.{"X11/"} },
    .{ "xfixes", &.{"X11/"} },
    .{ "xkbcommon", &.{"xkbcommon/"} },
    .{ "wayland-client", &.{ "wayland-client.h", "wayland-client-core.h", "wayland-client-protocol.h", "wayland-util.h", "wayland-version.h" } },
};

/// A package's headers as system include paths (so warnings in them stay
/// quiet), from pkg-config at configure time. Works for cross targets too,
/// unlike zig's native path detection. Falls back to the package's own
/// subtrees of its includedir (pkg-config strips -I/usr/include) or, when
/// pkg-config doesn't know the package at all (Arch's glm ships no .pc), of
/// the system include dirs.
pub fn addPkgConfigIncludes(b: *std.Build, m: *std.Build.Module, pkg: []const u8) void {
    const entries = for (pc_header_entries) |e| {
        if (std.mem.eql(u8, e[0], pkg)) break e[1];
    } else null;

    const includedir: []const u8 = switch (b.runFallible(&.{ "pkg-config", "--cflags-only-I", pkg }, .{ .stderr_behavior = .ignore })) {
        .success => |out| blk: {
            var found = false;
            var it = std.mem.tokenizeAny(u8, out, " \t\r\n");
            while (it.next()) |flag| {
                if (!std.mem.startsWith(u8, flag, "-I")) continue;
                m.addSystemIncludePath(.{ .cwd_relative = flag[2..] });
                found = true;
            }
            if (found) return;
            break :blk std.mem.trim(u8, pkgConfig(b, &.{ "--variable=includedir", pkg }), " \t\r\n");
        },
        .spawn_failed => std.process.fatal("eng: pkg-config not found (run inside `devenv shell`, or install pkg-config)", .{}),
        .bad_exit_code, .crashed => systemIncludeDirWith(b, pkg, entries orelse
            std.process.fatal("eng: pkg-config doesn't know '{s}' (install its development package, or use devenv)", .{pkg})),
    };

    const isolated = b.addWriteFiles();
    for (entries orelse std.process.fatal(
        "eng: pkg-config gave no include dir for '{s}' and build.zig doesn't know which headers it owns (add it to pc_header_entries)",
        .{pkg},
    )) |entry| {
        if (std.mem.endsWith(u8, entry, "/")) {
            const dir = entry[0 .. entry.len - 1];
            _ = isolated.addCopyDirectory(.{ .cwd_relative = b.pathJoin(&.{ includedir, dir }) }, dir, .{});
        } else {
            _ = isolated.addCopyFile(.{ .cwd_relative = b.pathJoin(&.{ includedir, entry }) }, entry);
        }
    }
    m.addSystemIncludePath(isolated.getDirectory());
}

/// The first system include dir (the ones pkg-config itself treats as system:
/// PKG_CONFIG_SYSTEM_INCLUDE_PATH, else /usr/include and /usr/local/include)
/// holding a package's headers, for packages with no .pc file.
fn systemIncludeDirWith(b: *std.Build, pkg: []const u8, entries: []const []const u8) []const u8 {
    const dirs = b.graph.environ_map.get("PKG_CONFIG_SYSTEM_INCLUDE_PATH") orelse "/usr/include:/usr/local/include";
    var it = std.mem.tokenizeScalar(u8, dirs, ':');
    while (it.next()) |dir| {
        const probe = std.mem.trimEnd(u8, entries[0], "/");
        std.Io.Dir.cwd().access(b.graph.io, b.pathJoin(&.{ dir, probe }), .{}) catch continue;
        return dir;
    }
    std.process.fatal("eng: '{s}' not found by pkg-config or in {s} (install its development package, or use devenv)", .{ pkg, dirs });
}

/// Runs pkg-config, turning failures into a readable message instead of a
/// crash in the build script.
fn pkgConfig(b: *std.Build, args: []const []const u8) []const u8 {
    const argv = std.mem.concat(b.allocator, []const u8, &.{ &.{"pkg-config"}, args }) catch @panic("OOM");
    return switch (b.runFallible(argv, .{ .stderr_behavior = .inherit })) {
        .success => |out| out,
        .spawn_failed => std.process.fatal("eng: pkg-config not found (run inside `devenv shell`, or install pkg-config)", .{}),
        .bad_exit_code, .crashed => std.process.fatal(
            "eng: `pkg-config {s}` failed — is the package's development package installed? (devenv provides all of them)",
            .{std.mem.join(b.allocator, " ", args) catch @panic("OOM")},
        ),
    };
}

/// Links eng into a game: libeng.a, the Vulkan loader, libsteam_api if this
/// eng dependency was built with Steam, and eng's public macros.
///
/// Use this rather than a bare `linkLibrary`. Include paths and system
/// libraries propagate from the artifact, but C macros, library search paths
/// and prebuilt objects don't. Whether Steam is in is read from the
/// dependency itself (and ENG_HAVE_STEAM arrives via eng/config.h), so the
/// game can't disagree with libeng.a about it.
pub fn link(b: *std.Build, exe: *std.Build.Step.Compile, eng_dep: *std.Build.Dependency) void {
    const m = exe.root_module;
    const target = m.resolved_target.?;
    const is_windows = target.result.os.tag == .windows;
    m.linkLibrary(eng_dep.artifact("eng"));
    addPublicMacros(m, is_windows);
    for (pc_headers_common) |pkg| addPkgConfigIncludes(b, m, pkg);
    if (is_windows) {
        // vulkan-1.dll import library, generated from the loader's export list.
        const dlltool = b.addSystemCommand(&.{ b.graph.zig_exe, "dlltool", "-m", "i386:x86-64", "-d" });
        dlltool.addFileArg(eng_dep.path("third_party/vulkan/vulkan-1.def"));
        dlltool.addArg("-l");
        m.addObjectFile(dlltool.addOutputFileArg("libvulkan-1.a"));
    } else {
        m.addObjectFile(.{ .cwd_relative = vulkanLoader(b) });
        // An old-glibc target (x86_64-linux-gnu.2.31) links against this
        // machine's libvulkan, which references newer glibc symbols than the
        // target has; only its DT_NEEDED matters, players' own loader resolves
        // against their glibc. The trade-off: undefined symbols in *any*
        // shared library (e.g. a libsteam_api.so update) then only show up at
        // runtime, so this is limited to explicit-glibc builds — native dev
        // builds keep the check and will catch them.
        if (target.query.glibc_version != null) exe.linker_allow_shlib_undefined = true;
    }
    if (eng_dep.builder.named_lazy_paths.get("steam_api_link")) |lp| m.addObjectFile(lp);
}

/// The build machine's Vulkan loader, linked only for its soname
/// (libvulkan.so.1, which every system with a Vulkan driver has).
fn vulkanLoader(b: *std.Build) []const u8 {
    const libdir = std.mem.trim(u8, pkgConfig(b, &.{ "--variable=libdir", "vulkan" }), " \t\r\n");
    if (libdir.len == 0) std.process.fatal("eng: pkg-config's vulkan.pc has no libdir", .{});
    // The unversioned libvulkan.so is a dev-package symlink some distros
    // split out; the versioned one ships with the loader itself.
    for ([_][]const u8{ "libvulkan.so", "libvulkan.so.1" }) |name| {
        const path = b.pathJoin(&.{ libdir, name });
        std.Io.Dir.cwd().access(b.graph.io, path, .{}) catch continue;
        return path;
    }
    std.process.fatal("eng: no libvulkan.so or libvulkan.so.1 in {s} (install the Vulkan loader)", .{libdir});
}

/// Macros that must match between eng and everything compiled against its
/// headers (option-dependent ones go in the generated eng/config.h instead).
fn addPublicMacros(m: *std.Build.Module, is_windows: bool) void {
    m.addCMacro("GLFW_INCLUDE_NONE", "1"); // no OpenGL anywhere; skips <GL/gl.h>
    if (is_windows) {
        m.addCMacro("WIN32_LEAN_AND_MEAN", "");
        m.addCMacro("NOMINMAX", "");
        // No _WIN32_WINNT: zig predefines it from the target's minimum OS
        // (Windows 10, 0x0A00 by default — also Steam's minimum), and a
        // second definition conflicts with it.
    }
}

const SteamLibKind = enum { link, runtime };

fn steamLib(is_windows: bool, kind: SteamLibKind) []const u8 {
    const dir = steam_sdk ++ "/redistributable_bin/";
    if (!is_windows) return dir ++ "linux64/libsteam_api.so";
    return switch (kind) {
        .link => dir ++ "win64/steam_api64.lib",
        .runtime => dir ++ "win64/steam_api64.dll",
    };
}

/// Per-executable Steam runtime plumbing, if this eng dependency was built
/// with Steam (otherwise a no-op): rpath $ORIGIN on Linux (libsteam_api.so
/// sits next to the binary), and installs the Steam runtime library plus the
/// game's steam_appid.txt into bin/. Hooked to the install step; also
/// returned, for steps that install only part of a project.
pub fn installSteamRuntime(
    b: *std.Build,
    eng_dep: *std.Build.Dependency,
    exe: *std.Build.Step.Compile,
    appid_file: std.Build.LazyPath,
) *std.Build.Step {
    const step = b.step(b.fmt("{s}-steam-runtime", .{exe.name}), "Install the Steam runtime next to the binary");
    if (eng_dep.builder.named_lazy_paths.get("steam_api_runtime")) |runtime| {
        const is_windows = exe.rootModuleTarget().os.tag == .windows;
        if (!is_windows) exe.root_module.addRPathSpecial("$ORIGIN");
        const name = std.fs.path.basename(steamLib(is_windows, .runtime));
        step.dependOn(&b.addInstallFileWithDir(runtime, .bin, name).step);
        step.dependOn(&b.addInstallFileWithDir(appid_file, .bin, "steam_appid.txt").step);
    }
    b.getInstallStep().dependOn(step);
    return step;
}
